from telegram import Update
from telegram.ext import ContextTypes

import db

TIPS_TEXT = """\
🧠 <b>Как начать думать на английском уже сейчас</b>

1. Проговаривай простые бытовые действия на английском мысленно: \
"I'm making coffee", "I need to reply to this email", "Let's check the schedule". \
Начни с рутинных вещей — это не требует словарного запаса, только привычка.

2. Когда не хватает слова — не переключайся на русский, а опиши мысль другими \
словами ("the thing that measures pressure" вместо "gauge"). Это тренирует \
именно свободную речь, а не перевод.

3. Смени язык интерфейса на телефоне и в паре приложений на английский — \
мелочь, но десятки маленьких "внутренних переводов" в день складываются в привычку.

4. Веди мини-дневник мыслей: 2-3 предложения в конце дня на английском о том, \
что произошло. Не важно, с ошибками — важна регулярность.

5. Слушай короткие подкасты или видео на английском и повторяй вслух фразы \
следом за диктором (shadowing) — это тренирует не понимание, а именно порождение речи.

6. Перед тем как сказать что-то важное на работе (даже по-русски), мысленно \
прикинь, как бы ты сформулировал это по-английски. Со временем этот шаг \
станет автоматическим.

7. Учи не отдельные слова, а готовые фразы-блоки (как раз то, что я присылаю \
каждый день) — мозгу проще думать связками "let's touch base" или "as far as I \
know", чем собирать фразу из отдельных слов заново каждый раз.

Начни с одного пункта, не пытайся сделать всё сразу — например, только \
пункт 1 в течение недели, потом добавь следующий.
"""


async def cmd_tips(update: Update, context: ContextTypes.DEFAULT_TYPE):
    db.touch_activity(update.effective_chat.id)
    await update.message.reply_text(TIPS_TEXT, parse_mode="HTML")
